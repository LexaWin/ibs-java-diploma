package ru.ibs.diploma.datamanagement;

/**
 * Перечень независимых входных наборов данных, которые могут запрашиваться
 * аналитическими командами по отдельности или совместно.
 */
public enum DataSource {
    /** Парковочные нарушения из CSV- или JSON-файла. */
    PARKING,
    /** Записи о рыночной стоимости и жилой площади недвижимости. */
    PROPERTIES,
    /** Численность населения по ZIP-кодам. */
    POPULATION
}

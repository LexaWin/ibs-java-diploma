package ru.ibs.diploma.logging;

/**
 * Абстракция журналирования событий приложения.
 * Позволяет компонентам записывать диагностические сообщения, не завися
 * от конкретного способа хранения журнала.
 */
public interface ApplicationLogger {
    /**
     * Записывает одно диагностическое событие.
     *
     * @param message текст события; обработка {@code null} определяется реализацией
     */
    void log(String message);
}
